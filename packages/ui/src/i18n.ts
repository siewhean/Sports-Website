export function interpolate(message: string, values: Record<string, string | number>) {
  return message.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token));
}

export function formatDateTime(
  value: Date | number | string,
  options: Intl.DateTimeFormatOptions = {},
  locale = defaultLocale,
  timeZone = defaultTimeZone,
) {
  return new Intl.DateTimeFormat(locale, { timeZone, ...options }).format(new Date(value));
}

export function formatNumber(value: number, locale = defaultLocale) {
  return new Intl.NumberFormat(locale).format(value);
}

export function formatCurrency(value: number, currency = "SGD", locale = defaultLocale) {
  return new Intl.NumberFormat(locale, { style: "currency", currency }).format(value);
}
