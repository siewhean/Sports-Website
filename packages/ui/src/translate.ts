export type PrototypeMessageId = keyof typeof prototypeMessages;
export type MessageValues = Record<string, string | number>;

export function opaqueId<const Value extends string>(value: Value): Value {
  return value;
}

const placeholderPattern = /\{([A-Za-z][A-Za-z0-9_]*)\}/g;

function interpolateMessage(message: string, values: MessageValues) {
  return message.replace(placeholderPattern, (token, key: string) => String(values[key] ?? token));
}

export function pseudoLocalise(message: string) {
  const expanded = message.replace(/\{[A-Za-z][A-Za-z0-9_]*\}|[A-Za-z]+/g, (token) => {
    if (token.startsWith("{")) return token;
    return token
      .replaceAll("a", "àà")
      .replaceAll("A", "ÀÀ")
      .replaceAll("e", "ëë")
      .replaceAll("E", "ËË")
      .replaceAll("i", "ïï")
      .replaceAll("I", "ÏÏ")
      .replaceAll("o", "öö")
      .replaceAll("O", "ÖÖ")
      .replaceAll("u", "üü")
      .replaceAll("U", "ÜÜ");
  });
  return "[!! " + expanded + " !!]";
}

function mapCatalogue(transform: (message: string) => string): Record<PrototypeMessageId, string> {
  return Object.fromEntries(
    Object.entries(prototypeMessages).map(([id, message]) => [id, transform(message)]),
  ) as Record<PrototypeMessageId, string>;
}

export const prototypeCatalogues: Record<SupportedLocale, Record<PrototypeMessageId, string>> = {
  "en-SG": prototypeMessages,
  "en-XA": mapCatalogue(pseudoLocalise),
  ar: mapCatalogue((message) => "\u2067" + message + "\u2069"),
};

export function directionForLocale(locale: SupportedLocale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function translate(
  id: PrototypeMessageId,
  values: MessageValues = {},
  locale: SupportedLocale = "en-SG",
): string {
  if (!Object.prototype.hasOwnProperty.call(prototypeMessages, id)) {
    throw new Error("Missing prototype message: " + String(id));
  }

  return interpolateMessage(prototypeCatalogues[locale][id], values);
}

export function createTranslator(locale: SupportedLocale) {
  return (id: PrototypeMessageId, values: MessageValues = {}) => translate(id, values, locale);
}
